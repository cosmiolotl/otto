#[test]
fn ln_1p_matches_js_log1p() {
    for (c, &bits) in JS_LOG1P_COMBO.iter().enumerate() {
        let v = (c as f64 * 1.25).ln_1p();
        assert_eq!(v.to_bits(), bits, "log1p(1.25 * {c}): rust {v:e} js {:e}", f64::from_bits(bits));
    }
    for (k, &bits) in JS_LOG1P_B2B.iter().enumerate() {
        let v = (k as f64 * 0.8).ln_1p();
        assert_eq!(v.to_bits(), bits, "log1p(0.8 * {k})");
    }
}
